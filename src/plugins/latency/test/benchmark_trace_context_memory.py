def wrap_sync(name):
    original = getattr(worker, name)
    def measured(*call_args, **kwargs):
        started = time.perf_counter()
        result = original(*call_args, **kwargs)
        extra = {}
        if isinstance(result, tuple) and len(result) >= 3:
            frame = result[2]
            if hasattr(frame, 'estimated_size'):
                extra['frame_mib'] = round(frame.estimated_size('mb'), 2)
                extra['frame_rows'] = frame.height
        mark(name, started, **extra)
        return result
    setattr(worker, name, staticmethod(measured))


def wrap_async(name):
    original = getattr(worker, name)
    async def measured(*call_args, **kwargs):
        started = time.perf_counter()
        result = await original(*call_args, **kwargs)
        extra = {}
        if name == '_ingest_log_failure_events' and isinstance(result, tuple):
            extra['inserted_rows'] = result[0]
            extra['trace_states'] = len(result[1])
        mark(name, started, **extra)
        return result
    setattr(worker, name, staticmethod(measured))


