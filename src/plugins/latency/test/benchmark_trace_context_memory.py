"""Offline context-store CPU/RSS benchmark; the sink never retains records.

Run each revision in a fresh process with the same thread count, for example:
  POLARS_MAX_THREADS=8 /root/witty-ub/src/plugins/latency/.venv/bin/python \
    src/plugins/latency/test/benchmark_trace_context_memory.py --source /root/witty-ub/src/plugins \
    --input /tmp/kvcache-memory-dense

The real manager conversion and COPY iteration remain enabled. Only database
connections and configuration lookup are replaced. Network/server costs are
excluded. --digest adds an order-sensitive digest over all stable row fields;
leave it disabled for throughput measurements. No AsyncMock is used: call
recording would itself retain every input batch and invalidate the RSS result.
The deterministic dense fixture is generated by:
  python src/plugins/latency/test/generate_kvcache_memory_fixture.py \
    /tmp/kvcache-context-dense --target-mib 300 --with-failures
Pass --with-failures to this benchmark to measure failure lookup construction.
"""
