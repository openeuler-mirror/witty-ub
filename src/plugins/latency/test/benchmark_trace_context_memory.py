    matched_traces = len(range(0, manifest['traces'], args.trace_step))
    trace_ids = {f'{number:08x}-9094-41bf-8204-e6b2ff438207'
                 for number in range(0, max(manifest['traces'], args.selection_size), args.trace_step)}
    expected_rows = matched_traces * sum(manifest['records_per_trace'].values())
