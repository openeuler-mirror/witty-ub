page_size = os.sysconf('SC_PAGE_SIZE')


def rss_mib():
    with open('/proc/self/statm') as handle:
        return int(handle.read().split()[1]) * page_size / 1024**2


def mark(phase, started, **extra):
    report = {'phase': phase, 'seconds': round(time.perf_counter() - started, 4),
              'rss_mib': round(rss_mib(), 2),
              'peak_mib': round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024, 2),
              **extra}
    phases.append(report)
    print(json.dumps(report, sort_keys=True), flush=True)


def accept(table, record, positions):
    counters[table + '_rows'] += 1
    if table == 'log_failure_event':
        counters['raw_text_characters'] += len(record[positions['raw_text']] or '')
        counters['message_characters'] += len(record[positions['message']] or '')
    if args.digest:
        # log row IDs are uuid4; the remaining data must match across revisions.
        stable = tuple(value for index, value in enumerate(record)
                       if index != positions.get('id'))
        digests.setdefault(table, hashlib.blake2b(digest_size=20)).update(
            json.dumps(stable, ensure_ascii=False, default=str, separators=(',', ':')).encode('utf-8') + b'\n'
        )


def csv_records(data):
    """Decode sink CSV text/bytes into record tuples (unquoted \\N = NULL)."""
    import csv
    import io
    if isinstance(data, bytes):
        data = data.decode('utf-8')
    return [
        tuple(None if value == '\\N' else value for value in row)
        for row in csv.reader(io.StringIO(data))
    ]


class SinkDriver:
    async def copy_records_to_table(self, table, *, records, columns, **kwargs):
        counters[table + '_copy_calls'] += 1
        positions = {name: index for index, name in enumerate(columns)}
        count = 0
        if hasattr(records, '__aiter__'):
            async for record in records:
                accept(table, record, positions)
                count += 1
        else:
            for record in records:
                accept(table, record, positions)
                count += 1
        if args.sink_delay:
            await asyncio.sleep(args.sink_delay)
        else:
            await asyncio.sleep(0)
        return f'COPY {count}'

    async def copy_to_table(self, table, *, source, columns=None, **kwargs):
        counters[table + '_copy_calls'] += 1
        positions = None
        count = 0
        async for chunk in source:
            counters[table + '_csv_bytes'] += len(chunk)
            if args.digest:
                if positions is None:
                    positions = {name: index for index, name in enumerate(columns)}
                # Chunks end at record boundaries and context fields never
                # embed newlines, so each chunk decodes independently.
                for record in csv_records(chunk):
                    accept(table, record, positions)
            # Context fields cannot contain \n, so byte newlines == records.
            count += chunk.count(b'\n')
        if not args.digest:
            # accept() already counted rows under --digest.
            counters[table + '_rows'] += count
        if args.sink_delay:
            await asyncio.sleep(args.sink_delay)
        else:
            await asyncio.sleep(0)
        return f'COPY {count}'


class SinkConnection:
    async def get_raw_connection(self):
        return SimpleNamespace(driver_connection=driver)


class SinkSession:
    def add_all(self, objects):
        for item in objects:
            table = item.__tablename__
            columns = (manager._LOG_FAILURE_COPY_COLUMNS if table == 'log_failure_event'
                       else manager._TRACE_FAILURE_COPY_COLUMNS)
            accept(table, tuple(getattr(item, column) for column in columns),
                   {name: index for index, name in enumerate(columns)})
        counters['orm_batches'] += 1


driver = SinkDriver()


@asynccontextmanager
async def connection(*args, **kwargs):
    counters['connections'] += 1
    yield SinkConnection()


@asynccontextmanager
async def session(*args, **kwargs):
    yield SinkSession()


