#!/bin/bash
# Assemble an AVX2 openGauss server package into the existing RAG
# database image. The base image supplies the entrypoint and OS dependencies;
# the package replaces only /usr/local/opengauss.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_BASE_IMAGE="hub-harbor.oepkgs.net/neocopilot/opengauss@sha256:4fd44608ca3571d3ceb5bc2bc5cbcde131dde2ed2b8068ff3f58effc8c60d885"

usage() {
    cat <<'EOF'
Usage:
  build_opengauss_x86_image.sh SERVER_PACKAGE IMAGE_TAG [BASE_IMAGE]

SERVER_PACKAGE must be an AVX2 openGauss-Server-*.tar.bz2 generated by
build_opengauss_x86_package.sh. BASE_IMAGE defaults to the exact image used by
the existing Witty RAG deployment.
EOF
}

[ "$#" -ge 2 ] && [ "$#" -le 3 ] || { usage >&2; exit 2; }

case "$(uname -m)" in
x86_64 | amd64) ;;
*)
    echo "This image builder only supports x86_64/amd64 hosts; got $(uname -m)" >&2
    exit 1
    ;;
esac

SERVER_PACKAGE="$(realpath "$1")"
IMAGE_TAG="$2"
BASE_IMAGE="${3:-$DEFAULT_BASE_IMAGE}"

[ -f "$SERVER_PACKAGE" ] || { echo "Server package not found: $SERVER_PACKAGE" >&2; exit 1; }
case "$(basename "$SERVER_PACKAGE")" in
openGauss-Server-*.tar.bz2) ;;
*) echo "Expected an openGauss-Server-*.tar.bz2 package" >&2; exit 2 ;;
esac

BUILD_CONTEXT="$(mktemp -d)"
cleanup() {
    rm -rf -- "$BUILD_CONTEXT"
}
trap cleanup EXIT

mkdir -p "$BUILD_CONTEXT/rootfs"
tar -xjf "$SERVER_PACKAGE" -C "$BUILD_CONTEXT/rootfs"

docker build \
    --build-arg "BASE_IMAGE=$BASE_IMAGE" \
    --label "org.opencontainers.image.revision=22b8cbffbd33023b7be11e17297c11972ab2e378" \
    --label "com.witty-ub.opengauss.cpu-target=avx2" \
    -f "$SCRIPT_DIR/opengauss-x86.Dockerfile" \
    -t "$IMAGE_TAG" \
    "$BUILD_CONTEXT"

echo "Built image: $IMAGE_TAG"
